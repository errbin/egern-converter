"""Generate an opt-in device selector check through the production compiler."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit

from tools.egern_hub.device_parameters import apply_device_parameters
from tools.egern_hub.js_analysis import analyze_many, validate_generated

SOURCE = """const type = /iPad/.test($loon) ? 'iPad' : /iPhone/.test($loon) ? 'iPhone' : 'Mac';
$notification.post('Egern 设备参数', '当前选择：' + type, '这是模块设置值，不是自动检测的硬件型号。');
$done({});
"""


def generate(output, base_url):
    url = urlsplit(base_url)
    if url.scheme not in {'http', 'https'} or not url.netloc or url.query or url.fragment:
        raise ValueError('base-url must be an HTTP(S) site URL without query or fragment')
    script_url = base_url.rstrip('/') + '/_verification/device-type.js'
    report = analyze_many([(SOURCE, 'loon', json.dumps({}))], mode='native')[0]
    if report['errors']:
        raise ValueError('；'.join(report['errors']))
    validate_generated({'device-type': report['code']})
    module = {
        'name': 'Egern 设备参数检测',
        'description': '在模块设置中切换设备类型，再运行 Device type probe 查看通知；此选项默认 iPhone，不自动检测硬件。',
        'author': 'ErrBin',
        'scriptings': [{'generic': {'name': 'Device type probe', 'script_url': script_url}}],
    }
    sources = [{'id': 'probe', 'format': 'derived', 'script_map': {script_url: 'probe-script'},
                '_render_obj': module, '_render_header': '# Generated by verification/device_parameter_probe.py\n'}]
    resources = [{'id': 'probe'}]
    apply_device_parameters(sources, resources, [{'id': 'probe-script'}], {'probe-script': report})
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    (output / 'device-type.js').write_text(report['code'], encoding='utf-8')
    (output / 'device-type.yaml').write_text(resources[0]['yaml'], encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path('dist/_verification'))
    parser.add_argument('--base-url', required=True)
    args = parser.parse_args()
    generate(args.output, args.base_url)
    print(args.base_url.rstrip('/') + '/_verification/device-type.yaml')
